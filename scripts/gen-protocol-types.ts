// Generates src/protocol.ts from DemoVideoScript's published backend-protocol
// schema, so the arm's message types are the schema's, never restated by hand.
//
//   node scripts/gen-protocol-types.ts <backend-protocol.schema.json> [--check]
//
// With --check it fails when src/protocol.ts differs from what the schema
// generates (the schema changed and the types were not regenerated).
import { readFileSync, writeFileSync } from "node:fs";

type Schema = { [k: string]: any };

const [schemaPath, flag] = process.argv.slice(2);
if (!schemaPath) {
  console.error("usage: gen-protocol-types.ts <schema> [--check]");
  process.exit(64);
}
const root: Schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const defs: Schema = root.$defs ?? {};

function typeName(def: string): string {
  return def
    .split(/[-_]/)
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
}

function lit(v: unknown): string {
  return JSON.stringify(v);
}

function ts(s: Schema | boolean, indent = ""): string {
  if (s === true || s === undefined) return "unknown";
  if (s === false) return "never";
  if (s.$ref) return typeName(s.$ref.replace("#/$defs/", ""));
  if ("const" in s) return lit(s.const);
  if (s.enum) return s.enum.map(lit).join(" | ");
  if (s.oneOf || s.anyOf)
    return (s.oneOf ?? s.anyOf).map((x: Schema) => ts(x, indent)).join(" | ");
  const types: string[] = Array.isArray(s.type)
    ? s.type
    : s.type
      ? [s.type]
      : [];
  if (types.length > 1)
    return types.map((t) => ts({ ...s, type: t }, indent)).join(" | ");
  switch (types[0]) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `Array<${ts(s.items ?? true, indent)}>`;
    case "object": {
      const props: Schema = s.properties ?? {};
      const req = new Set<string>(s.required ?? []);
      const inner = indent + "  ";
      const lines = Object.entries(props).map(
        ([k, v]) =>
          `${inner}${JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${ts(v as Schema, inner)};`,
      );
      if (s.additionalProperties && s.additionalProperties !== false)
        lines.push(
          `${inner}[key: string]: ${ts(s.additionalProperties, inner)};`,
        );
      else if (
        s.additionalProperties !== false &&
        Object.keys(props).length === 0
      )
        lines.push(`${inner}[key: string]: unknown;`);
      return `{\n${lines.join("\n")}\n${indent}}`;
    }
  }
  return "unknown";
}

let out =
  "// GENERATED by scripts/gen-protocol-types.ts from DemoVideoScript's\n" +
  "// schemas/v1/backend-protocol.schema.json. Do not edit; regenerate.\n\n";
for (const [name, def] of Object.entries(defs)) {
  out += `export type ${typeName(name)} = ${ts(def as Schema)};\n\n`;
}
out += `export type Message = ${ts({ oneOf: root.oneOf })};\n`;

const target = new URL("../src/protocol.ts", import.meta.url);
if (flag === "--check") {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== out) {
    console.error(
      "src/protocol.ts is stale: run scripts/gen-protocol-types.ts",
    );
    process.exit(1);
  }
  console.log("src/protocol.ts matches the schema");
} else {
  writeFileSync(target, out);
}
